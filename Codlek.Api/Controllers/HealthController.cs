using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace Codlek.Api.Controllers;

/// <summary>
/// <c>/api/health</c> — الحيطة اللي كل راكة بتخبط عليها الأول،
/// و<c>/d/{code}</c> للّيبلات القديمة.
///
/// <para>🔴 <b>والاتنين <u>مفتوحين</u> عن قصد.</b> الراكة اللي
/// مفتاحها بقى غلط لازم تقدر تعرف إن السيرفر اتنقل، وليبل مطبوع
/// على لاب لازم يفتح لأي حد بيمسحه — والحاجز بييجي بعد التحويلة مش
/// قبلها.</para>
/// </summary>
[ApiController]
[AllowAnonymous]
public sealed class HealthController(IConfiguration config) : ControllerBase
{
    /// <summary>
    /// 🔴 <b>«أنا اتنقلت» — الطريقة اللي الراكات بتلحق بيها نقلة
    /// السيرفر.</b>
    ///
    /// <para>لو عنوان السيرفر اتغيّر، كل راكة في الميدان لسه شايلة
    /// العنوان القديم ومش هتعرف توصل. والراكات أجهزة بتشتغل أوفلاين
    /// لفترات، فالانتظار لحد ما حد يروح لكل واحدة ويكتب العنوان
    /// بإيده معناه شغل بيقف أيام.</para>
    ///
    /// <para>والحل: العنوان الجديد بيتحط في إعدادات السيرفر
    /// <b>القديم</b> وقت النقل (<c>Server__MovedTo</c>). أي راكة
    /// لسه بتوصل للقديم بتقراه، بتتأكد إن الجديد رادّ، وبتنقل نفسها
    /// — من غير ما حد يلمسها.</para>
    ///
    /// <para>🔴 <b>بيتحط على القديم بس، عمره ما يتحط على
    /// الجديد.</b> لو الاتنين بيعلنوا، الراكات بتفضل تلف بينهم
    /// للأبد.</para>
    ///
    /// <para>⚠️ <b>والخانة مابتتكتبش خالص لما تكون فاضية.</b>
    /// الراكة بتفحص وجود المفتاح نفسه، فإرسال <c>movedTo: null</c>
    /// كان بيتقري على إنه إعلان نقل لعنوان فاضي.</para>
    /// </summary>
    [HttpGet("api/health")]
    public IActionResult Health()
    {
        string movedTo = (config["Server:MovedTo"] ?? "").Trim();

        var now = DateTime.UtcNow;

        return movedTo.Length == 0
            ? Ok(new { ok = true, at = now })
            : Ok(new { ok = true, at = now, movedTo });
    }

    /// <summary>
    /// توافق قديم — <c>/d/{code}</c>.
    ///
    /// <para>⚠️ <b>ده مش عقد الـQR الجديد.</b> الليبل الجديد بيشيل
    /// الكود عارياً (<c>LP-00000001</c>) ومفيهوش رابط خالص، عشان
    /// يعيش بعد تغيير الاستضافة والمنفذ واسم السيرفر.</para>
    ///
    /// <para>بس ليبلات اتطبعت قبل كده من الراكة بتشيل
    /// <c>https://host/d/CODE</c>، وهي ملزوقة على أجهزة شغّالة
    /// دلوقتي. المسار ده بيخليها تفضل تشتغل — طول ما الـhost اللي
    /// مطبوع عليها لسه بيرد. وده بالظبط السبب اللي خلّى الشكل ده
    /// يتشال من الليبل الجديد.</para>
    ///
    /// <para>🔴 <b>والمسار مابيقراش من القاعدة ومابيقولش حاجة عن
    /// اللاب: بيحوّل وبس.</b> الحاجز هو صفحة الأجهزة نفسها، واللي
    /// مش داخل بيتحوّل للدخول من هناك. فمفيش تسريب، ومفيش عدّ أكواد
    /// من برّه.</para>
    ///
    /// <para>⚠️ <b>والكود بيتهرّب.</b> كود فيه مسافة أو
    /// <c>&amp;</c> كان بيكسر الرابط أو يضيف معامل مش موجود.</para>
    /// </summary>
    [HttpGet("d/{code}")]
    public IActionResult Scan(string code) =>
        Redirect("/app/devices?scan=" + Uri.EscapeDataString(code));
}
