namespace Codlek.Application.Contracts.Handover;

/// <summary>
/// معرّفات كل اللي طلع من الفلتر — <b>لزرار «اختر الكل»</b>.
///
/// <para>🔴 <b>موجودة لأن «ماينفعش أنزل ٣ صفحات وأعلّم في كل
/// واحدة».</b> القايمة بتجيب ٢٥ في الصفحة، فـ٥١ لاب جاهز معناهم
/// تلات صفحات وتعليم يدوي في كل واحدة — والغلطة الواحدة بتضيّع
/// الشغل كله.</para>
///
/// <para>⚠️ <b>وبترجّع معرّفات بس.</b> الصفوف الكاملة لـ٥٠٠ لاب
/// حِمل مالوش لازمة — الواجهة عندها الصفحة المعروضة بالتفصيل، وده
/// كل اللي ناقصها.</para>
/// </summary>
/// <param name="Total">
/// 🔴 <b>العدد قبل القص، مش بعده.</b> لو اتحسب بعد القص هيساوي عدد
/// اللي رجع دايماً و<see cref="Truncated"/> هيبقى <c>false</c> على
/// طول — يعني مدير عنده ٦٠٠ مرشّح ياخد ٥٠٠ والشاشة تقوله «٥٠٠ من
/// ٥٠٠»، فيسلّمهم وهو فاكر إنه خلّص الستمية.
/// </param>
/// <param name="Truncated">
/// ⚠️ لما نقص، بنقول إننا قصّينا. القص الصامت بيبان كأنك اخترت
/// الكل وإنت لأ.
/// </param>
public sealed record HandoverCandidateIds(
    IReadOnlyList<Guid> Ids,
    int Total,
    bool Truncated);
