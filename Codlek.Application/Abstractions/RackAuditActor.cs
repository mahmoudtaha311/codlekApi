namespace Codlek.Application.Abstractions;

/// <summary>
/// محطة فحص كـ«فاعل» في سجل المراجعة.
///
/// <para>🔴 <b>والنوع ده موجود عشان الشركة تبان صريحة.</b> سجل
/// المستخدم بيقرا الشركة من <c>ICurrentUser</c> — وطلب الراكة مالوش
/// توكن ومالوش مطالبات، و<c>ICurrentUser.TenantId</c> <b>بترمي</b>
/// لو اتندهت عليه. فالشركة لازم تيجي من المحطة المتحققة، والنوع ده
/// هو اللي بيخلّي ده مكتوب في التوقيع مش متروك للنية.</para>
///
/// <para>⚠️ <b>و<see cref="Ip"/> جزء من السجل مش زيادة.</b> المحطة
/// جهاز في الميدان، والعنوان هو الحاجة الوحيدة اللي بتفرّق بين
/// «المحطة اللي في الورشة» و«حد شايل نسخة من قرصها». وهو اللي بيخلّي
/// اشتباه الاستنساخ قابل للمراجعة بعد أسبوع.</para>
/// </summary>
/// <param name="Name">
/// ⚠️ اسم المحطة وقت الحدث — <b>لقطة</b>. تغيير الاسم بعدين مالوش
/// يعدّل سطور قديمة.
/// </param>
public sealed record RackAuditActor(
    Guid TenantId,
    Guid RackId,
    string Name,
    string Ip);
