using Codlek.Core.Entities;

namespace Codlek.Application.Interfaces;

/// <summary>
/// بيحوّل مفتاح محطة لمحطة — <b>أو لا شيء</b>.
///
/// <para>🔴 <b>وده البوابة الوحيدة لكل سطح الراكة.</b> تسع نقط
/// معتمدة عليه، ومفيش فيهم ولا واحدة بتاخد معرّف شركة من الطلب:
/// الشركة بتتقرا <b>من المحطة</b> بعد التحقق.</para>
///
/// <para>🔴 <b>الترتيب هو الأمان نفسه:</b></para>
///
/// <para>مفتاح المحطة ← المحطة ← شركتها ← الفني جوّه الشركة دي</para>
///
/// <para>ولو الطلب أخد <c>tenantId</c>، أي محطة مسروقة كانت هتفتح
/// فنيي <b>كل</b> الشركات.</para>
///
/// <para>⚠️ <b>و<c>null</c> معناها <c>401</c> بجسم فاضي — مش
/// <c>403</c> ومش رسالة.</b> اللي بيحاول مالوش يعرف إيه اللي ناقص:
/// مفتاح غلط، ولا محطة موقوفة، ولا محطة ملغية — كلهم نفس الرد.</para>
/// </summary>
public interface IRackAuthenticator
{
    /// <summary>
    /// المحطة اللي المفتاح ده بتاعها — ولازم تكون <b>نشطة</b>.
    ///
    /// <para>⚠️ والمحطة الموقوفة أو الملغية بتقع هنا، قبل ما أي
    /// اسم أو شركة يتقرا.</para>
    /// </summary>
    Task<Rack?> AuthenticateAsync(string? apiKey, CancellationToken ct = default);
}
