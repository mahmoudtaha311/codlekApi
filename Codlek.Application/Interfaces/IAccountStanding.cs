namespace Codlek.Application.Interfaces;

/// <summary>
/// حالة الحساب اللي كل طلب لوحة بيتفحص عليها — <b>متخزّنة ثواني</b>.
///
/// <para>🔴 <b>الفحص نفسه في التحقق من التوكن</b> (<c>AccountStanding</c>
/// في البنية التحتية). الواجهة دي موجودة عشان المعالجات اللي بتغيّر
/// الحالة تقول «انسى اللي عندك» — من غير ما تعرف إن فيه كاش أصلاً.</para>
/// </summary>
public interface IAccountStanding
{
    /// <summary>
    /// انسى حالة الحساب ده — الطلب الجاي بيقراها من القاعدة.
    ///
    /// <para>🔴 <b>بتتنده بعد الحفظ، مش قبله.</b> لو اتندهت قبله، طلب
    /// في النص يقرا الحالة القديمة ويخزّنها تاني — والإيقاف ياخد عمر
    /// الكاش بدل ما يبقى فوري.</para>
    ///
    /// <para>⚠️ <b>بتأثر على السيرفر ده بس.</b> لو فيه نسخة تانية شغّالة،
    /// الطرد هناك بياخد لحد عمر الكاش (ثواني) — مش ١٥ دقيقة.</para>
    /// </summary>
    void Forget(Guid userId);
}
