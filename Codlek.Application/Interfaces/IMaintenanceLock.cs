namespace Codlek.Application.Interfaces;

/// <summary>
/// قفل على مستوى القاعدة — <b>صيانة الإقلاع تشتغل في عملية واحدة بس</b>.
///
/// <para>🔴 <b>الاستضافة بتشغّل نسختين من البرنامج مع بعض ساعات.</b>
/// إعادة التدوير على IIS بتقوّم العملية الجديدة قبل ما القديمة تقفل.
/// من غير القفل، الاتنين بيمشوا على نفس الفحوص اليتيمة في نفس اللحظة
/// (شغل مكرر على استضافة صغيرة)، وعلى قاعدة فاضية الاتنين بيشوفوا «مفيش
/// شركة» ويعملوا شركتين.</para>
/// </summary>
public interface IMaintenanceLock
{
    /// <summary>
    /// بياخد القفل من غير استنّى — أو <c>null</c> لو عملية تانية ماسكاه.
    ///
    /// <para>⚠️ القفل بيتساب لما الناتج يتقفل، أو لوحده لو العملية
    /// وقعت (الاتصال بيتقطع).</para>
    /// </summary>
    Task<IAsyncDisposable?> TryAcquireAsync(string name, CancellationToken ct = default);
}
