namespace Codlek.Core.Devices;

/// <summary>
/// تتبّع سلسلة الدمج — <b>«موجود» معناها <u>حيّ</u> مش «ليه
/// صف»</b>.
///
/// <para>🔴 <b>والقاعدة دي اتكتبت بعد حادثة إنتاج.</b></para>
///
/// <para>راكة جديدة بتشوف لاب لأول مرة بتولّد له معرّف محلي خاص
/// بيها. لما ترفعه، السيرفر بيطابق مراسيه ويلاقيه <b>جهاز موجود
/// أصلاً</b> بمعرّف تاني، فبيعمل اسم مستعار بيربط المعرّف المحلي
/// بالكانوني وبيرجّع «اتقبل». وده الصح: الراكة مش مطالَبة تغيّر
/// معرّفها، والترجمة شغل السيرفر.</para>
///
/// <para>🔴 <b>والدمج <u>مابيمسحش</u> صف الجهاز المكرر</b> — بيسيبه
/// شاهد قبر بـ<c>Merged</c> و<c>MergedIntoDeviceId</c>. يعني معرّف
/// مدموج بيتلاقى في جدول الأجهزة وبيرجع <b>شاهد القبر</b>، والنتيجة
/// في الإنتاج: شغل بيتربط بجهاز ميّت، أو بيترفض بـ«الجهاز ده مدموج
/// في جهاز تاني».</para>
///
/// <para>⚠️ <b>الدرس:</b> أي فحص «الجهاز ده موجود؟» في مسار بيستقبل
/// من راكة لازم يعدّي من هنا. لو لقيت بحث مباشر في جدول الأجهزة في
/// مسار زي كده، <b>ده عيب مش أسلوب</b>.</para>
/// </summary>
public static class DeviceMergeChain
{
    /// <summary>
    /// سقف تتبّع السلسلة — أ مدموج في ب مدموج في ج.
    ///
    /// <para>⚠️ السلسلة المفروض تبقى قصيرة جداً، بس السقف موجود عشان
    /// بيانات بايظة (حلقة مقفولة) تطلع «مش معروف» بدل ما <b>تعلّق
    /// الطلب للأبد</b>.</para>
    /// </summary>
    public const int MaxHops = 10;

    /// <summary>
    /// 🔴 <b>وسلسلة الاسم المستعار مش بتتصلّح وقت الدمج.</b>
    ///
    /// <para>الدمج بيضيف اسم مستعار جديد وبس — مابيعيدش توجيه
    /// الأسامي القديمة. فـ«أ ← ب» اللي اتعمل قبل «ب ← ج» بيفضل
    /// بيشاور على <b>ب</b>، وب بقى شاهد قبر. عشان كده التتبّع هنا
    /// بيلفّ: الاسم المستعار بيوصّلنا لصف، والصف لو شاهد قبر
    /// بيوصّلنا للي بعده.</para>
    /// </summary>
    public const string WhyChainsExist =
        "الدمج بيضيف اسم مستعار جديد ومابيعيدش توجيه القديم";
}
