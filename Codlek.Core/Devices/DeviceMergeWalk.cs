namespace Codlek.Core.Devices;

/// <summary>
/// المشي من معرّف جهاز لمعرّفه الكانوني — <b>القواعد النقية</b>.
///
/// <para>🔴 <b>البحث المباشر هنا كان سبب عطل حقيقي في الإنتاج:</b>
/// حركات اترفضت لجهاز <b>وصل فعلاً</b> بس بمعرّف تاني. اللاب الواحد
/// بيوصل للسيرفر بمعرّفات مختلفة من راكات مختلفة، والدمج بيخلّي واحد
/// منهم هو الكانوني — والباقي بيبقوا أسماء مستعارة.</para>
///
/// <para>⚠️ <b>والكود اللي بيلمس القاعدة منفصل عن ده عن قصد.</b>
/// القواعد هنا (الحد الأقصى للخطوات · كشف الحلقة · المعرّف الفاضي)
/// كلها بتتفحص من غير قاعدة بيانات؛ والمشي نفسه في
/// <c>Infrastructure</c>.</para>
/// </summary>
public static class DeviceMergeWalk
{
    /// <summary>
    /// أقصى عدد خطوات في سلسلة الدمج.
    ///
    /// <para>🔴 <b>الحد ده مش تحسين، هو حماية.</b> سلسلة دمج طويلة
    /// معناها بيانات بايظة، ومن غير الحد المشي بيلفّ للأبد والطلب
    /// بيعلّق — <b>والراكة اللي مستنية الرد بتعيد المحاولة</b>،
    /// فالحمل بيتضاعف.</para>
    ///
    /// <para>⚠️ وعشرة رقم كبير جداً عملياً: أطول سلسلة شوفناها كانت
    /// خطوتين.</para>
    /// </summary>
    public const int MaxHops = 10;

    /// <summary>
    /// الخطوة دي مسموحة؟
    ///
    /// <para>⚠️ بترجّع <c>false</c> لو المعرّف ده اتزار قبل كده —
    /// يعني حلقة. ودي بيانات بايظة: جهاز «أ» مدموج في «ب» و«ب» مدموج
    /// في «أ».</para>
    /// </summary>
    public static bool CanVisit(HashSet<Guid> seen, Guid next) => seen.Add(next);

    /// <summary>
    /// المعرّف ده ينفع يُسأل عنه أصلاً؟
    ///
    /// <para>🔴 <c>Guid.Empty</c> مش «مش موجود» — هو «مابعتليش
    /// حاجة». والفرق بيبان في السجل: استعلام على
    /// <c>00000000-...</c> بيرجّع فاضي ويتسجّل «الجهاز مش موجود»،
    /// والحقيقة إن الطلب كان ناقص.</para>
    /// </summary>
    public static bool IsAskable(Guid deviceId) => deviceId != Guid.Empty;

    /// <summary>
    /// الصف ده مدموج في جهاز تاني؟ — <b>وفي أنهي واحد</b>.
    /// </summary>
    /// <returns>
    /// معرّف الجهاز الكانوني لو الصف مدموج فعلاً، و<c>null</c> لو ده
    /// آخر السلسلة.
    /// </returns>
    /// <remarks>
    /// ⚠️ <b>التلات شروط مع بعض.</b> صف حالته <c>Merged</c> و
    /// <c>MergedIntoDeviceId</c> فاضي = بيانات ناقصة، واتباعها بيوصل
    /// لـ<c>Guid.Empty</c> ويرجّع «مش موجود». فبنوقف عنده ونعتبره
    /// الكانوني — أهون من حركة بتترفض.
    /// </remarks>
    public static Guid? MergedInto(
        Enums.DeviceLifecycleStatus status, Guid? mergedIntoDeviceId) =>
        status == Enums.DeviceLifecycleStatus.Merged
        && mergedIntoDeviceId is { } into
        && into != Guid.Empty
            ? into
            : null;
}
