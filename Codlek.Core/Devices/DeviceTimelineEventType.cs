namespace Codlek.Core.Devices;

/// <summary>
/// نوع الحدث على خط زمن اللاب.
///
/// <para>⚠️ <b>ده نوع عرض، مش رقم على السلك.</b> الراكة مابتقراهوش
/// — اللي بيتعرض للواجهة هو <b>اسم</b> القيمة كنص
/// (<c>TestPerformed</c>)، والواجهة بتختار الأيقونة بيه. فالأرقام
/// هنا داخلية، بخلاف <c>Codlek.Core/Enums</c> اللي أرقامها
/// مجمّدة.</para>
///
/// <para><b>والأرقام مثبّتة بردو عن قصد.</b> القيم من <b>١٠٠
/// وطالع</b> محجوزة للشغل التشغيلي، عشان حد ما يعيد ترقيم اللي فوق.
/// والقاعدة اللي الملف ده ماشي عليها: <b>مفيش قيمة بتتضاف قبل ما
/// يبقى فيه جدول بيسجّلها</b> — قيمة ماحدّش بينتجها بتوعد بحاجة مش
/// موجودة.</para>
///
/// <para>🔴 <b>والأرقام دي بتدخل مفتاح الترتيب عن طريق
/// <c>DeviceTimelineOrder.Rank</c>، مش على طول.</b> اللي بيفك
/// التعادل هو رقم <b>الأولوية</b> مش رقم الـenum — فزيادة قيمة هنا
/// لازم يتقابلها سطر في <c>Rank</c>، وإلا الحدث بياخد الأولوية
/// الافتراضية ويقع آخر أي مجموعة متعادلة من غير سبب.</para>
/// </summary>
public enum DeviceTimelineEventType
{
    DeviceDiscovered = 1,
    TestPerformed = 2,
    NoteAdded = 3,

    // ===== الشغل التشغيلي — المدى المحجوز =====

    /// <summary>اتفتح أمر صيانة.</summary>
    RepairOpened = 100,

    /// <summary>بدأت الصيانة.</summary>
    RepairStarted = 101,

    /// <summary>تمت الصيانة — الأمر اتقفل وحالته «تمت».</summary>
    RepairCompleted = 102,

    /// <summary>
    /// تعذّر الإصلاح.
    ///
    /// <para>🔴 <b>نوع مستقل عن <see cref="RepairCompleted"/> عن
    /// قصد.</b> الاتنين بيقفلوا الأمر في نفس العمود، بس واحد معناه
    /// اللاب بقى جاهز والتاني معناه لسه فيه عطل. دمجهم في سطر واحد
    /// بلون واحد بيخلّي خط الزمن يقول «خلصت» على شغل ما خلصش.</para>
    /// </summary>
    RepairUnableToRepair = 103,

    /// <summary>اتلغى أمر الصيانة.</summary>
    RepairCancelled = 104,

    /// <summary>
    /// حركة تشغيلية على اللاب.
    ///
    /// <para>⚠️ <b>نوع واحد لكل الحركات، مش نوع لكل
    /// <c>DeviceWorkflowEventType</c>.</b> الفرق بين «اتنقل لمكان»
    /// و«اتسلّم لفني» بيتقال في عنوان السطر وملخّصه، واللي بيحتاجه
    /// مفتاح الترتيب هو أولوية واحدة. سبع قيم في المدى ٠—٩ بتاع
    /// <c>Rank</c> كانت هتاكل المدى كله وتخلّي أي إضافة جاية تكسر
    /// المقارنة النصية.</para>
    /// </summary>
    DeviceMoved = 110,
}
