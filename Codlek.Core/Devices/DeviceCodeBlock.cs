namespace Codlek.Core.Devices;

/// <summary>
/// بلوك أكواد أجهزة — <b>القواعد النقية</b>.
///
/// <para>🔴 <b>والبلوك ده هو اللي بيخلّي الراكة تشتغل أوفلاين.</b>
/// الفني بيفحص لاب جديد وهو مقطوع عن النت، واللاب محتاج كود فوراً
/// عشان الليبل يتطبع. فالسيرفر بيأجّر للراكة مدى أرقام محجوز ليها،
/// وهي بتوزّعه بنفسها لحد ما تتصل تاني.</para>
/// </summary>
public static class DeviceCodeBlock
{
    /// <summary>حجم البلوك الافتراضي.</summary>
    public const int DefaultSize = 500;

    /// <summary>
    /// أكبر بلوك.
    ///
    /// <para>⚠️ <b>والسقف ده عن قصد:</b> البلوك القديم بيتقفل من
    /// غير ما يرجع للمساحة، فأي أرقام متستخدمتش فيه بتفضل
    /// <b>فجوة للأبد</b>. وراكة بتطلب بلوك ضخم كل دورة بتاكل مدى
    /// الأكواد بسرعة.</para>
    /// </summary>
    public const int MaxSize = 2000;

    /// <summary>
    /// الحجم الفعلي — <b>مقصوص مش مرفوض</b>.
    ///
    /// <para>⚠️ <c>size=0</c> أو قيمة سالبة أو غايبة بتروح
    /// للافتراضي، مش <c>400</c>: الراكة في الميدان ومش المفروض تقف
    /// عشان معامل. و<c>size=99999</c> بياخد السقف.</para>
    /// </summary>
    public static int Size(int? requested) =>
        Math.Clamp(requested is null or <= 0 ? DefaultSize : requested.Value, 1, MaxSize);

    /// <summary>
    /// الكود المقروء من رقم — <c>LP-00000001</c>.
    ///
    /// <para>🔴 <b>تمن خانات بأصفار على الشمال — والشكل ده
    /// مجمّد.</b> الليبل المطبوع على اللاب شايله، ومسح الباركود
    /// بيطابقه <b>مطابقة تامة</b>. أي تغيير في الحشو معناه إن كل
    /// استيكر في الورشة مابقاش بيطابق.</para>
    /// </summary>
    public static string Format(int number) => "LP-" + number.ToString("00000000");
}
