namespace Codlek.Core.Handover;

/// <summary>
/// قواعد التسليم اللي مالهاش علاقة بقاعدة البيانات.
///
/// <para>⚠️ شرط الأهلية نفسه عايش في الاستعلام (مستودع التسليم) —
/// هو سؤال عن صفوف. اللي هنا هو الأرقام والحدود اللي بتتقال
/// للمستخدم.</para>
/// </summary>
public static class HandoverPolicy
{
    /// <summary>
    /// أكبر دفعة في المرة — <b>للتسليم وللمراجعة ولاختيار
    /// الكل</b>.
    ///
    /// <para>🔴 <b>رقم واحد لتلاتتهم عن قصد.</b> «اختر كل اللي طلع»
    /// بيرجّع لحد الرقم ده، والتسليم بيرفض أكتر منه. ولو اتنين
    /// اختلفوا، المدير بيختار دفعة النقطة التانية بترفضها كلها
    /// ومايفهمش ليه.</para>
    /// </summary>
    public const int BatchLimit = 500;

    /// <summary>
    /// أقصر اسم مستلم مقبول.
    ///
    /// <para>⚠️ حرف واحد مش اسم — ودي الخانة اللي بتجاوب «هاني سلّم
    /// لمين الشهر ده».</para>
    /// </summary>
    public const int MinReceiverName = 2;

    /// <summary>
    /// 🔴 <b>أقصر سبب مقبول للتسليم من غير مراجعة.</b>
    ///
    /// <para>الباب المقفول بالكامل بيتحايل عليه: حالة مستعجلة
    /// والمراجعة مقفولة معناها إن حد هيعلّم «جاهز» على السريع عشان
    /// يعدّي — وساعتها المراجعة تبقى ختم مالوش معنى وإحنا مش عارفين
    /// إن ده حصل.</para>
    ///
    /// <para>⚠️ فالباب مفتوح <b>بشرط إنه يتكتب</b>. والفرق بين
    /// استثناء وخرق إن الاستثناء متسجّل. و«ok» مش سبب — عشان كده
    /// فيه حد أدنى.</para>
    /// </summary>
    public const int MinOverrideReason = 10;

    /// <summary>
    /// أكبر عدد أكواد بتتقال في رسالة الرفض.
    ///
    /// <para>⚠️ الرسالة بتقول أنهي لاب بالكود — «فيه لاب مش مؤهّل»
    /// بتخلّي اللي بيراجع يلغي الدفعة كلها وهو مش عارف ليه. بس
    /// ٥٠٠ كود في رسالة واحدة مش رسالة.</para>
    /// </summary>
    public const int BlockedCodesShown = 5;

    /// <summary>
    /// ⚠️ <c>take</c> موجود عشان حد الدفعة <b>يتقاس</b>: من غيره،
    /// السلوك عند تخطّي السقف مايتجرّبش غير بزرع ٥٠١ جهاز في قاعدة
    /// الفحوص. والقيمة بتتقص على السقف فمفيش طريق تطلب أكتر منه.
    /// </summary>
    public static int Cap(int? take) => Math.Clamp(take ?? BatchLimit, 1, BatchLimit);

    /// <summary>
    /// فلتر المراجعة — <b>تلات شاشات مختلفة</b>.
    ///
    /// <para>🔴 والافتراضي <see cref="ReviewFilter.Reviewed"/> عن
    /// قصد: لو كان «الكل»، صفحة التسليم بترجع لسلوكها القديم
    /// بالظبط والمراجعة تبقى شاشة مالهاش أثر.</para>
    /// </summary>
    public static ReviewFilter Review(string? value) =>
        (value ?? "").Trim().ToLowerInvariant() switch
        {
            "pending" => ReviewFilter.NotReviewed,
            "all" => ReviewFilter.Any,
            _ => ReviewFilter.Reviewed,
        };
}
