namespace Codlek.Core.Time;

/// <summary>
/// تاريخ مكتوب بالعربي المصري: «الإثنين، 16 سبتمبر 2026».
///
/// <para>🔴 <b>الأسماء مكتوبة هنا مش مأخوذة من إعدادات
/// النظام.</b> بيانات اللغات على السيرفر ممكن تكون ناقصة أو تدّي
/// «كانون الأول» بدل «ديسمبر» — وده مش اللي بيتقال في مصر.</para>
///
/// <para>⚠️ <b>والأرقام لاتينية هنا، بخلاف رسايل التسليم.</b> ده
/// اللي المشروع القديم بيطلّعه بالحرف، والمشروعين هيشتغلوا على نفس
/// القاعدة فترة التحويل — فنفس اليوم لازم يتكتب بنفس الشكل من
/// الشاشتين. (رسايل التسليم هناك مكتوبة بأرقام عربية-هندية، وده
/// تفريق موجود في القديم ومنقول زي ما هو.)</para>
///
/// <para>⚠️ وده للعرض بس — مفيش حاجة بتتقارن ولا بتتخزّن بالشكل
/// ده.</para>
/// </summary>
public static class ArabicDate
{
    private static readonly string[] Days =
    [
        "الأحد", "الإثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت",
    ];

    private static readonly string[] Months =
    [
        "يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو",
        "يوليو", "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر",
    ];

    public static string Long(DateTime date) =>
        $"{Days[(int)date.DayOfWeek]}، {date.Day} {Months[date.Month - 1]} {date.Year}";
}
