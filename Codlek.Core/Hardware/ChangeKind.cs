namespace Codlek.Core.Hardware;

/// <summary>
/// نتيجة مقارنة مكوّن واحد — <b>حقيقة، مش استنتاج</b>.
///
/// <para>🔴 <b>الاسم هو اللي بيتبعت على السلك، مش الرقم.</b>
/// المقارنة بترجّع <c>Kind.ToString()</c> في الرد، فالواجهة بتقرا
/// <c>"SerialChanged"</c> — يعني <b>إعادة التسمية</b> هي اللي
/// بتكسر، مش إعادة الترقيم. (بخلاف enums الراكة اللي أرقامها هي
/// العقد.)</para>
///
/// <para>⚠️ <b>والافتراضي هو الشك مش اليقين.</b>
/// <see cref="IdentityUncertain"/> و<see cref="NotObserved"/> هما
/// الرد الطبيعي، والكلام القاطع استثناء لازم يستاهله الدليل: الحكم
/// ده بيتحوّل لاتهام إن موظف غيّر قطعة.</para>
/// </summary>
public enum ChangeKind
{
    /// <summary>هوية قوية اتطابقت والبيانات زي ما هي.</summary>
    Unchanged = 0,

    /// <summary>هوية قوية جديدة ظهرت، والغياب القديم متأكّد منه.</summary>
    Added = 1,

    /// <summary>هوية قوية قديمة اختفت، والغياب <b>متأكّد منه</b>.</summary>
    Removed = 2,

    /// <summary>
    /// اتطابقوا عن طريق <b>مكان ثابت وفريد</b>، والسيريال نفسه
    /// اتغيّر.
    ///
    /// <para>⚠️ مينفعش تتقال من غير المكان الثابت — سيريالين
    /// مختلفين من غير رابط بينهم مش «اتغيّر»، دول حاجتين مالهمش
    /// علاقة.</para>
    /// </summary>
    SerialChanged = 3,

    /// <summary>
    /// نفس الهوية القوية، بس نص الموديل اتغيّر (فيرموير أو قراءة).
    /// </summary>
    ModelChanged = 4,

    /// <summary>هوية ضعيفة، والتكوين مختلف.</summary>
    ConfigurationDifferent = 5,

    /// <summary>مقدرناش نطابق بثقة — <b>مش</b> معناه إن حاجة اتغيّرت.</summary>
    IdentityUncertain = 6,

    /// <summary>الفئة دي ماتفحصتش في اللقطة — الغياب <b>مش</b> مثبت.</summary>
    NotObserved = 7
}
