namespace Codlek.Core.Hardware;

/// <summary>
/// اسم درجة ثقة الهوية.
///
/// <para>⚠️ <b>المشروع القديم فيه تلات نسخ مختلفة من الأسماء
/// دي</b> — واحدة بتقول «ج» وواحدة «ج — كود متلزّق» وواحدة بتقول
/// «—». اللي اتنقل هو نسخة الواجهة الجديدة، وهي النسخة الوحيدة
/// هنا.</para>
///
/// <para>🔴 والدرجة دي هي أهم عمود في الجدول: هي اللي بتقول للّي
/// بيقرا هل «اتغيّرت» دليل ولا احتمال.</para>
/// </summary>
public static class IdentityConfidenceText
{
    public static string Arabic(int confidence) => confidence switch
    {
        1 => "أ — سيريال حقيقي",
        2 => "ب — بصمة تحدّد الموديل",
        3 => "ج — مسار جهاز",
        _ => "مفيش",
    };
}
