namespace Codlek.Core.Hardware;

/// <summary>
/// نتيجة مرحلة فحص — النص والترتيب.
///
/// <para>🔴 <b>الترتيب <u>مش</u> رقم الحالة.</b> الترقيم المخزّن
/// اعتباطي (١ شغال · ٢ فيه مشكلة · ٣ اتخطّى · ٤ مش موجود · ٥ ما
/// اشتغلش)، فالمقارنة الرقمية المباشرة بتقول إن «مش موجود» أحسن من
/// «فيه مشكلة» — والشاشة بتقول «الجهاز اتحسّن» وهو في الحقيقة
/// باظ.</para>
/// </summary>
public static class StepOutcome
{
    /// <summary>
    /// نص الحالة.
    ///
    /// <para>⚠️ أي رقم جديد من نسخة أحدث بينزل في الافتراضي بدل ما
    /// يقع. الأرقام مثبّتة ومابتتغيّرش، فالقيمة المجهولة معناها
    /// «نسخة أحدث» وبس.</para>
    /// </summary>
    public static string Arabic(int status) => status switch
    {
        1 => "نجح",
        2 => "فشل",
        3 => "تم التخطّي",
        4 => "غير موجود بالجهاز",
        5 => "تعذّر التنفيذ",
        6 => "قيد الفحص",
        _ => "لم يُنفّذ",
    };

    /// <summary>
    /// ترتيب «الأحسن» بين الحالات — <b>رقم للمقارنة بس</b>.
    ///
    /// <para>شغال أحسن حاجة · بعده «مش موجود» (دي حالة طبيعية مش
    /// عطل) · بعده «لسه» · بعده «اتخطّى» و«ما اشتغلش» (نقص فحص) ·
    /// وأسوأ حاجة «فيه مشكلة».</para>
    ///
    /// <para>⚠️ الرقم ده مابيتعرضش ومابيتخزّنش — هو مدخل للمقارنة
    /// وبس.</para>
    /// </summary>
    public static int Rank(int status) => status switch
    {
        1 => 5,   // شغال
        4 => 4,   // مش موجود — معلومة مواصفات مش عطل
        0 => 3,   // لسه
        3 => 2,   // اتخطّى
        5 => 1,   // الفحص ما اشتغلش
        2 => 0,   // فيه مشكلة
        _ => 3,
    };

    /// <summary>
    /// اتجاه التغيير بين فحصين لنفس المرحلة.
    ///
    /// <para>⚠️ ومفيش مجموع ولا درجة: كل مرحلة بتتقال لوحدها.
    /// «الفحص اتحسّن ٢٠٪» جملة مالهاش معنى — الجهاز إما البطارية
    /// بتاعته بقت أحسن أو لأ.</para>
    /// </summary>
    public static string Direction(int? left, int? right) =>
        left is null ? "OnlyRight"
        : right is null ? "OnlyLeft"
        : left == right ? "Same"
        : Rank(right.Value) > Rank(left.Value) ? "Improved"
        : "Regressed";
}
