using Codlek.Core.Enums;

namespace Codlek.Core.Repairs;

/// <summary>
/// سياسة أوامر الصيانة — <b>سطر واحد بيشغّل الميزة على كل الراكات</b>.
/// </summary>
public static class RepairPolicy
{
    /// <summary>
    /// حالة الموافقة اللي الأمر الجديد بيتعمل بيها.
    ///
    /// <para>🔴 <b>السطر ده هو اللي بيشغّل منع الموافقة كله.</b>
    /// الراكة بتقرا <c>ApprovalEnforced</c> من قدرات السيرفر، وهي
    /// محسوبة من المقارنة <c>NewOrderApproval == Pending</c> — يعني
    /// تغيير السطر ده لوحده بيفتح ويقفل المنع على <b>الراكات
    /// كلها</b>.</para>
    ///
    /// <para>⚠️ <b>والراكة اللي لسه بنسخة قديمة مابتتكسرش.</b> هي مش
    /// عارفة الموافقة فمش بتمنع، والفني بيشتغل عادي — والسيرفر
    /// <b>بيقبل</b> شغله ويعلّمه
    /// (<c>RepairWorkItem.StartedWithoutApproval</c>) بدل ما يرفضه،
    /// لأن الرفض في طابور الرفع <b>نهائي</b> وبيمسح شغل اتعمل فعلاً.</para>
    ///
    /// <para>⚠️ وفيه فحص بيثبّت القيمة الحالية — تغييرها قرار واعي
    /// مش سهو.</para>
    /// </summary>
    public const RepairApproval NewOrderApproval = RepairApproval.Pending;

    /// <summary>
    /// المنع شغّال؟ — <b>ودي اللي الراكة بتقراها</b>.
    ///
    /// <para>⚠️ محسوبة مش مكتوبة، عشان مايبقاش فيه مكانين للحقيقة.</para>
    /// </summary>
    public static bool ApprovalEnforced => NewOrderApproval == RepairApproval.Pending;

    /// <summary>
    /// نتأكد من ماركة اللاب ولا لأ؟
    ///
    /// <para>🔴 <b>مفيش قيمة افتراضية هنا عن قصد.</b> كل مكان بيسأل
    /// لازم يقول نيّته بالاسم. الافتراضي كان هيخلّي أي مسار جديد
    /// يتكتب بعدين ياخد المنع في صمت — <b>ومن ضمنها مسارات قفل
    /// الأمر</b>، واللي معناها إن صيانة خلصت فعلاً مترفضش تتسجّل.</para>
    /// </summary>
    public enum BrandCheck
    {
        /// <summary>اتأكد — ده إسناد شغل جديد.</summary>
        Enforce,

        /// <summary>
        /// ماتتأكدش.
        ///
        /// <para>🔴 <b>للأفعال اللي بتسجّل شغل حصل خلاص.</b> اللاب
        /// اتصلّح؛ رفض تسجيل النتيجة مش بيمنع حاجة — بيمسح الدليل
        /// على شغل اتعمل. ولو الفني اتشالت منه الماركة بعد ما اشتغل،
        /// منعه من إنه يقفل أمره بيسيب الأمر مفتوح للأبد.</para>
        /// </summary>
        Skip,
    }
}
