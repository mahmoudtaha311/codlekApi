using System;
using System.Collections.Generic;
using System.Text;

namespace Codlek.Core.Text;
/// <summary>
/// تطبيع النص العربي للبحث — <b>سياسة واحدة للنظام كله</b>.
///
/// <para><b>ليه الملف ده موجود.</b> اتجرّب فعلاً إن
/// <c>Arabic_CI_AI</c> على SQL Server <b>مش</b> بيخلي «أحمد» تساوي
/// «احمد»، و<c>Arabic_CI_AS</c> نفس النتيجة بالظبط. السبب إن الهمزة
/// حرف مستقل في يونيكود مش علامة تشكيل، فالـ collation مبيشيلهاش.
/// يعني اختيار الـ collation — أي collation — مش هيحل المشكلة دي،
/// والحل الوحيد تطبيع في التطبيق.</para>
///
/// <para><b>ليه ده مهم عملياً.</b> اسم الفني بيتكتب بأشكال مختلفة
/// («أحمد» / «احمد» / «احمـد»)، والمدير بيدوّر بالاسم. من غير تطبيع
/// البحث بيرجع فاضي والمستخدم بيفتكر إن الشغل مش موجود.</para>
///
/// <hr/>
///
/// <para><b>اللي بيتطبّع (وكله اختلافات كتابة لنفس الحرف):</b></para>
/// <list type="bullet">
/// <item>ألفات الهمزة: <c>أ إ آ ٱ</c> ← <c>ا</c></item>
/// <item>همزة على واو وياء: <c>ؤ ئ</c> ← <c>و ي</c></item>
/// <item>التشكيل كله (فتحة/ضمة/كسرة/شدة/سكون/تنوين) بيتشال</item>
/// <item>التطويل <c>ـ</c> بيتشال</item>
/// <item>الألف المقصورة <c>ى</c> ← <c>ي</c></item>
/// <item>التاء المربوطة <c>ة</c> ← <c>ه</c></item>
/// <item>حروف فارسية/أردية بتيجي من النسخ واللصق: <c>ک ی ھ</c> ← <c>ك ي ه</c></item>
/// <item>الأرقام العربية-الهندية <c>٠١٢…</c> و<c>۰۱۲…</c> ← <c>012…</c></item>
/// <item>المسافات المتكررة بتتلم، والحروف اللاتينية بتبقى كابيتال</item>
/// </list>
///
/// <para><b>واللي <u>مش</u> بيتطبّع عن قصد:</b> الهمزة المفردة
/// <c>ء</c> بتفضل زي ما هي، وأي حرفين مختلفين فعلاً
/// (<c>س/ص</c> · <c>د/ذ</c> · <c>ه/ح</c> · <c>ت/ط</c>) عمرهم ما
/// بيتدمجوا. التطبيع هدفه يوحّد <b>شكل كتابة نفس الحرف</b>، مش يزوّد
/// عدد النتايج على حساب صحتها.</para>
///
/// <para>⚠️ <b>قرار متعمّد فيه مقايضة:</b> <c>ى ← ي</c> بيخلي «على»
/// و«علي» يطابقوا بعض. دول كلمتين مختلفتين في المعنى، بس في الكتابة
/// اليومية — وبالذات في الأسماء — الاتنين بيتكتبوا بالتبادل. الملف ده
/// بيغذّي <b>البحث</b> بس، مش مقارنة هوية ولا مطابقة سيريالات، فخسارة
/// الدقة هنا مقبولة مقابل إن المدير يلاقي شغل الفني.</para>
///
/// <para>⚠️ <b>ممنوع استخدام الملف ده في مطابقة هوية.</b> مراسي
/// الأجهزة بتتطبّع بـ <c>DeviceMatcher.Normalize</c> — دي قواعد تانية
/// خالص (بتحافظ على كل حرف) لأن دمج سيريالين مختلفين معناه دمج
/// جهازين.</para>
///
/// <hr/>
///
/// <para>⚠️⚠️ <b>الملف ده متكرّر حرفياً في المشروعين:</b>
/// <c>spics/Text/ArabicText.cs</c> و<c>web/CodlekWeb/Text/ArabicText.cs</c>.
/// لازم يفضلوا <b>متطابقين بايت ببايت</b> — لو اختلفوا، النص المتخزّن
/// على السيرفر هيبقى متطابع بقاعدة والبحث بقاعدة تانية، والنتيجة بحث
/// بيرجع فاضي من غير أي رسالة خطأ.</para>
///
/// <para>مااتعملش ملف مشترك بالربط (<c>Link</c>) عن قصد: سياق بناء
/// الـ Docker بتاع الموقع هو <c>./CodlekWeb</c> بس، فملف برّه السياق
/// ده مش هيتلاقى والنشر هيقع. التكرار + فحص تلقائي بيقارن الملفين
/// أأمن من ربط بيكسر البناء.</para>
///
/// <para>أداة التحقق بتقارن الملفين وبترفض أي اختلاف.</para>
/// </summary>
public static class ArabicText
{
    /// <summary>
    /// حالات اختبار مشتركة — <b>نفس القيم في النسختين</b>.
    ///
    /// <para>كل عنصر: النص الداخل ثم الناتج المتوقّع. الاختبار في
    /// المشروعين بيمشي على نفس القايمة، فأي اختلاف في السلوك بيبان
    /// على طول مش بعد ما البحث يفضل فاضي في الإنتاج.</para>
    /// </summary>
    public static readonly string[][] Vectors =
    {
        // المثال اللي القرار اتاخد عليه
        new[] { "أحمد", "احمد" },
        new[] { "إبراهيم", "ابراهيم" },
        new[] { "آمنة", "امنه" },

        // التشكيل والتطويل
        new[] { "مُحَمَّد", "محمد" },
        new[] { "مـحـمـد", "محمد" },
        new[] { "أَحْمَد", "احمد" },

        // الهمزة على واو وياء
        new[] { "مسؤول", "مسوول" },
        new[] { "قائمة", "قايمه" },

        // التاء المربوطة والألف المقصورة
        new[] { "شاشة", "شاشه" },
        new[] { "مصطفى", "مصطفي" },

        // حروف فارسية بتيجي من النسخ واللصق
        new[] { "کيبورد", "كيبورد" },
        new[] { "بطاری", "بطاري" },

        // الأرقام
        new[] { "١٢٣", "123" },
        new[] { "شاشة ١٤ بوصة", "شاشه 14 بوصه" },

        // المسافات والحروف اللاتينية
        new[] { "  HP   EliteBook  ", "HP ELITEBOOK" },
        new[] { "hp elitebook", "HP ELITEBOOK" },

        // فاضي
        new[] { "", "" },
        new[] { "   ", "" },

        // ⚠️ حروف مختلفة فعلاً — لازم تفضل مختلفة
        new[] { "سعد", "سعد" },
        new[] { "صعد", "صعد" },
        new[] { "حسن", "حسن" },
        new[] { "هسن", "هسن" },

        // الهمزة المفردة بتفضل
        new[] { "جزء", "جزء" }
    };

    /// <summary>
    /// بيرجّع الشكل المطبَّع للبحث.
    ///
    /// <para>القيمة دي هي اللي بتتخزّن في أعمدة البحث <b>وهي اللي
    /// المستخدم بيتطبّع عليها وقت السؤال</b> — الطرفين لازم يعدّوا من
    /// نفس الدالة، وإلا المقارنة بتبقى بين شكلين مختلفين.</para>
    /// </summary>
    public static string Normalize(string? value)
    {
        if (string.IsNullOrWhiteSpace(value)) return "";

        var output = new StringBuilder(value.Length);
        bool pendingSpace = false;

        foreach (char raw in value)
        {
            if (IsRemovable(raw)) continue;

            char c = Map(raw);

            if (char.IsWhiteSpace(c))
            {
                // المسافات بتتلم لواحدة، والبداية بتتشال.
                if (output.Length > 0) pendingSpace = true;
                continue;
            }

            if (pendingSpace)
            {
                output.Append(' ');
                pendingSpace = false;
            }

            output.Append(c);
        }

        return output.ToString();
    }

    /// <summary>
    /// بيجمّع أكتر من حقل في نص بحث واحد.
    ///
    /// <para>الفاصل مسافة عشان كلمة من آخر حقل ما تلزقش في أول اللي
    /// بعده وتعمل تطابق وهمي.</para>
    /// </summary>
    public static string Combine(params string?[] parts)
    {
        var output = new StringBuilder(128);

        foreach (string? part in parts)
        {
            string normalized = Normalize(part);
            if (normalized.Length == 0) continue;

            if (output.Length > 0) output.Append(' ');
            output.Append(normalized);
        }

        return output.ToString();
    }

    /// <summary>
    /// الحرف ده بيتشال خالص؟ (تشكيل أو تطويل أو علامات اتجاه)
    /// </summary>
    private static bool IsRemovable(char c)
    {
        // التشكيل العربي: فتحتين/ضمتين/كسرتين/فتحة/ضمة/كسرة/شدة/سكون
        if (c >= 'ً' && c <= 'ٟ') return true;

        // الألف الخنجرية والعلامات القرآنية
        if (c == 'ٰ') return true;
        if (c >= 'ۖ' && c <= 'ۭ') return true;

        // التطويل — حرف تزيين مالوش أي معنى في البحث
        if (c == 'ـ') return true;

        // علامات اتجاه النص — مش مرئية وبتتلزق مع النسخ واللصق
        if (c >= '​' && c <= '‏') return true;
        if (c >= '‪' && c <= '‮') return true;

        return false;
    }

    /// <summary>
    /// بيحوّل الحرف لشكله الموحّد.
    ///
    /// <para>كل تحويل هنا بين <b>شكلين كتابة لنفس الحرف</b>. مفيش أي
    /// تحويل بين حرفين مختلفين فعلاً.</para>
    /// </summary>
    private static char Map(char c)
    {
        switch (c)
        {
            // ألفات الهمزة ← ألف
            case 'آ': // آ
            case 'أ': // أ
            case 'إ': // إ
            case 'ٱ': // ٱ
                return 'ا'; // ا

            // همزة على واو ← واو
            case 'ؤ': return 'و'; // ؤ ← و

            // همزة على ياء ← ياء
            case 'ئ': return 'ي'; // ئ ← ي

            // الألف المقصورة ← ياء (شوف التحذير في وصف الكلاس)
            case 'ى': return 'ي'; // ى ← ي

            // التاء المربوطة ← هاء
            case 'ة': return 'ه'; // ة ← ه

            // حروف فارسية/أردية بتيجي من لوحات مفاتيح أو نسخ ولصق
            case 'ک': return 'ك'; // ک ← ك
            case 'ی': return 'ي'; // ی ← ي
            case 'ھ': return 'ه'; // ھ ← ه
            case 'ہ': return 'ه'; // ہ ← ه
        }

        // الأرقام العربية-الهندية ← لاتينية
        if (c >= '٠' && c <= '٩') return (char)('0' + (c - '٠'));

        // الأرقام الفارسية ← لاتينية
        if (c >= '۰' && c <= '۹') return (char)('0' + (c - '۰'));

        // اللاتيني كابيتال عشان البحث ما يبقاش حسّاس لحالة الحروف
        if (c >= 'a' && c <= 'z') return (char)(c - 32);

        return c;
    }

    /// <summary>
    /// بيتأكد إن كل حالات الاختبار بتعدّي.
    /// بيرجّع قايمة الاختلافات — فاضية معناها كل حاجة تمام.
    /// </summary>
    public static List<string> SelfTest()
    {
        var failures = new List<string>();

        foreach (string[] pair in Vectors)
        {
            string actual = Normalize(pair[0]);
            if (actual == pair[1]) continue;

            failures.Add($"«{pair[0]}» ← متوقّع «{pair[1]}» وطلع «{actual}»");
        }

        return failures;
    }
}
