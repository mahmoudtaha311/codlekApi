namespace Codlek.Core.Text;

/// <summary>
/// مفتاح الدخول المطبَّع — <b>القاعدة الوحيدة اللي الهوية بتتحدد بيها</b>.
///
/// <para><b>ليه الملف ده اتعمل، وليه القواعد اللي جوّه بالظبط.</b>
/// قبل كده مكانش فيه تطبيع لأسماء الدخول خالص. اللي كان بيحصل فعلاً
/// حاجتين: <c>Trim()</c> في صفحة الدخول، وبعدها مقارنة بترتيب القاعدة
/// <c>Arabic_CI_AI</c> (مش حسّاسة لحالة الحروف). يعني <b>السياسة
/// الحقيقية</b> اللي النظام ماشي بيها من الأول هي «شيل المسافات على
/// الطرفين، وحالة الحروف مش فارقة». الملف ده بيكتب السياسة دي صراحةً
/// في عمود، مش بيخترع سياسة جديدة.</para>
///
/// <para><b>وليه مش <c>ArabicText.Normalize</c>.</b> الملف ده مكتوب
/// عليه بالنص إنه <b>ممنوع في مطابقة الهوية</b>، وبحق: هو بيعمل
/// <c>ى ← ي</c> و<c>ة ← ه</c> عشان البحث يرجّع نتايج أكتر. على اسم
/// دخول ده معناه إن حسابين لشخصين مختلفين يتلموا في مفتاح واحد.
/// البحث لو وسّع شوية، أسوأ حاجة نتيجة زيادة؛ الدخول لو وسّع، واحد
/// بيدخل على حساب حد تاني.</para>
///
/// <para><b>وليه مش <c>IdentityValues.Normalize</c>.</b> دي لسيريالات
/// العتاد: بتلمّ المسافات <b>اللي في النص</b> وبتعمل كابيتال. اسم
/// الدخول مالوش مسافات جوّاه أصلاً، وخلطه بقواعد العتاد بيربط حاجتين
/// مالهمش علاقة — أي تعديل في مطابقة السيريالات كان هيغيّر مين يقدر
/// يدخل.</para>
///
/// <para>⚠️ <b>الخرج بحروف صغيرة عن قصد</b> — نفس اللي البرنامج
/// المكتبي بيعمله في <c>AccountRepository</c>
/// (<c>Username.ToLower() == needle.ToLower()</c>). الطرفين لازم
/// يوصلوا لنفس المفتاح، وإلا اسم يدخل على الراكة ومايدخلش على الموقع.</para>
///
/// <para>⚠️ <c>ToLowerInvariant</c> مش <c>ToLower</c>: الأخيرة بتعتمد
/// على لغة السيرفر، ولو السيرفر اتظبط على تركي بقت <c>I</c> بتنزل
/// <c>ı</c> مش <c>i</c> — ونفس الاسم يبقى ليه مفتاحين حسب مكان
/// التشغيل.</para>
/// </summary>
public static class LoginName
{
    /// <summary>أطول مفتاح — نفس طول عمود <c>Username</c>.</summary>
    public const int MaxLength = 60;

    /// <summary>
    /// بيرجّع المفتاح اللي البحث والفهرس الفريد بيشتغلوا عليه.
    ///
    /// <para>القيمة دي بتتخزّن في عمود، <b>والمستخدم بيتطبّع عليها وقت
    /// الدخول</b> — الطرفين لازم يعدّوا من هنا، وإلا المقارنة بتبقى بين
    /// شكلين مختلفين.</para>
    /// </summary>
    public static string Normalize(string? value)
    {
        if (string.IsNullOrWhiteSpace(value)) return "";

        string trimmed = value.Trim().ToLowerInvariant();

        // القص هنا مش تجميل: العمود طوله محدود، ولو القيمة عدّت من غير
        // قص، الحفظ بيقع بخطأ من القاعدة بدل رسالة مفهومة.
        return trimmed.Length <= MaxLength ? trimmed : trimmed[..MaxLength];
    }
}
