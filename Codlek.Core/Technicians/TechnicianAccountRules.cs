namespace Codlek.Core.Technicians;

/// <summary>
/// قواعد حساب الفني — <b>الأطوال والحدود</b>.
///
/// <para>🔴 <b>وتلات قواعد لازم تتنفّذ مع بعض في كل مرة:</b> الاسم
/// فريد <b>جوّه الشركة</b>، والكود ثابت بعد الإنشاء، ونسخة البيانات
/// بتزيد مع كل تغيير باسورد أو إيقاف. ولو الكلام ده اتكتب في مكانين،
/// تاني مكان بينسى واحدة — والنسيان هنا <b>مش خطأ ظاهر</b>: نسخة
/// محفوظة على راكة أوفلاين بتفضل صالحة بعد ما المدير يعتقد إنه
/// ألغاها.</para>
/// </summary>
public static class TechnicianAccountRules
{
    public const int MinDisplayName = 2;

    /// <summary>
    /// ⚠️ تلات حروف — أقل من كده اسم دخول بيتلخبط مع كود.
    /// </summary>
    public const int MinUsername = 3;

    /// <summary>
    /// ⚠️ <b>أربعة بس — ومنقولة زي ما هي.</b> الفني بيكتبه على
    /// شاشة لمس في ورشة، والطول الكبير بيخلّيه يكتبه على ورقة
    /// ويلزقها على الراكة. والحماية الحقيقية هي عدّاد المحاولات
    /// وإن الدخول من راكة متحققة بمفتاحها.
    /// </summary>
    public const int MinPassword = 4;

    /// <summary>
    /// 🔴 <b>سبب الإيقاف إجباري — والفني بيشوفه على الراكة.</b>
    ///
    /// <para>من غير سبب، الفني بيقف قدام رسالة مقفولة ومش عارف
    /// يكلّم مين، فبيروح يجرّب حساب زميله — وده بالظبط اللي الإيقاف
    /// بيمنعه.</para>
    /// </summary>
    public const int MinSuspendReason = 3;

    /// <summary>
    /// ⚠️ عدد محاولات توليد كود فاضي قبل ما نستسلم.
    ///
    /// <para>والرمي بعدها مقصود: ٤٠ محاولة فاشلة معناها إن مجال
    /// الأكواد (٩٠٠ ألف) خلص تقريباً — ودي حاجة المدير لازم يعرفها،
    /// مش كود مكرر يتحشر في القاعدة.</para>
    /// </summary>
    public const int CodeAttempts = 40;

    /// <summary>
    /// 🔴 <b><see cref="Guid.Empty"/> في القسم معناها «شيل
    /// القسم».</b>
    ///
    /// <para>القسم الفاضي في القاعدة هو <c>null</c>، و<c>null</c>
    /// في الطلب محجوزة لـ«ماتلمسش» — فمحتاجين قيمة حارسة تفرّق بين
    /// «المدير شال القسم بقرار» و«عميل قديم نسي يبعت الحقل».
    /// و<c>Guid.Empty</c> عمرها ما تكون معرّف قسم حقيقي، فمفيش
    /// تعارض.</para>
    /// </summary>
    public static Guid? Department(Guid? sent) =>
        sent is { } value ? (value == Guid.Empty ? null : value) : null;
}
