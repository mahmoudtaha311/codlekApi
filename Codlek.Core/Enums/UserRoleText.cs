namespace Codlek.Core.Enums;

/// <summary>
/// اسم الدور بالعربي — <b>مصدر واحد</b>.
///
/// <para>🔴 <b>النصوص دي بتتعرض للمستخدم فعلاً</b> في شريط الحساب
/// وقايمة المستخدمين، وبتخرج في عقد <c>AccountResponse.RoleText</c>.
/// يعني أي تغيير هنا بيبان في الشاشة على طول.</para>
///
/// <para>⚠️ <b>وكانوا مكتوبين في مكانين واختلفوا فعلاً.</b> نسخة في
/// <c>WebUser.RoleText</c> ونسخة في زرع الأدوار، والاتنين كانوا بيقولوا
/// حاجات مختلفة: «مدير عام» مقابل «مالك»، و«مدير المخزن» مقابل «مدير».
/// فاللي بيقرا من العقد بيشوف اسم واللي بيقرا من جدول الأدوار بيشوف
/// اسم تاني — لنفس الشخص.</para>
///
/// <para>⚠️ <b>والأسماء مش ترجمة حرفية للـenum، دي مسمّيات الورشة.</b>
/// <c>Manager</c> هو «مدير المخزن» و<c>Owner</c> هو «مدير عام» —
/// ماتصلّحهمش عشان تخليهم «مطابقين» للإنجليزي.</para>
/// </summary>
public static class UserRoleText
{
    public static string Arabic(UserRole role) => role switch
    {
        UserRole.Owner => "مدير عام",
        UserRole.Manager => "مدير المخزن",
        UserRole.FloorManager => "مدير الدور",
        UserRole.Accountant => "محاسب",

        // ⚠️ الافتراضي «فني» مش رمي. دور جديد في الـenum بيبان باسم
        // مفهوم لحد ما حد يضيف اسمه — بدل ما الشاشة تقع.
        _ => "فني",
    };
}
