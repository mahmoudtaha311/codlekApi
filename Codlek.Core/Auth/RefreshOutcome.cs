namespace Codlek.Core.Auth;

/// <summary>
/// نتيجة فحص توكن تجديد.
///
/// <para>⚠️ <b>الأسباب منفصلة عن قصد، وبرضه كلها بتترفض عند الزبون
/// بنفس الرسالة.</b> التفرقة دي للسجل: فرق بين «مستخدم فضل أسبوع من
/// غير ما يفتح» و«حد بيحاول يستعمل توكن مسروق». الأول عادي والتاني
/// لازم حد ياخد باله.</para>
/// </summary>
public enum RefreshOutcome
{
    /// <summary>التجديد مسموح — اعمل توكن جديد ولفّ القديم.</summary>
    Allowed = 0,

    /// <summary>
    /// التوكن موقّع صح بس مفيش صف ليه.
    ///
    /// <para>⚠️ ده معناه واحد من اتنين: صف اتمسح في التنضيف، أو
    /// التوكن من قاعدة تانية بنفس المفتاح. الاتنين «لأ».</para>
    /// </summary>
    UnknownToken = 1,

    /// <summary>
    /// 🔴 <b>توكن اتبدّل قبل كده واتقدّم تاني — دليل سرقة.</b>
    ///
    /// <para>التجديد بيلغي القديم ويعمل جديد. فلو القديم رجع تاني،
    /// يبقى فيه نسختين منه: واحدة عند صاحبه وواحدة عند حد تاني. مفيش
    /// سبب شريف يخلّي ده يحصل.</para>
    ///
    /// <para><b>والرد الصح إن السلسلة كلها تتقفل</b>، مش إن الطلب ده
    /// يترفض وبس — لأن لو الحرامي هو اللي عنده الجديد، رفض الطلب ده
    /// بيطرد صاحب الحساب ويسيب الحرامي شغّال.</para>
    /// </summary>
    Reused = 2,

    /// <summary>اتلغى بالنيّة — خروج أو المدير قفله. مش سرقة.</summary>
    Revoked = 3,

    /// <summary>عدّى عمره.</summary>
    Expired = 4,

    /// <summary>
    /// بيانات الاعتماد اتغيّرت بعد ما التوكن اتعمل.
    ///
    /// <para>🔴 <b>ده هو الطرد.</b> تغيير باسورد أو إيقاف حساب بيزوّد
    /// <c>CredentialVersion</c>، فأي توكن قديم بيترفض هنا.</para>
    /// </summary>
    CredentialsChanged = 5,

    /// <summary>الحساب موقوف.</summary>
    AccountDisabled = 6
}
